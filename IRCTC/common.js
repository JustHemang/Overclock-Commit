let currentLang = localStorage.getItem('irctc_lang') || 'en';

function t(key) { return LANG_STRINGS[currentLang]?.[key] || LANG_STRINGS.en[key] || key; }

function applyLanguage() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') el.placeholder = t(key);
    else el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-opt]').forEach(el => {
    el.textContent = t(el.dataset.i18nOpt);
  });
}

function selectLang(lang) {
  currentLang = lang;
  localStorage.setItem('irctc_lang', lang);
  sessionStorage.setItem('welcomeShown', 'true');
  const overlay = document.getElementById('welcomeOverlay');
  if (overlay) overlay.classList.add('hidden');
  applyLanguage();
  if (typeof window.runTrainAnimation === 'function') {
    window.runTrainAnimation();
  }
}



function toggleLang() {
  selectLang(currentLang === 'en' ? 'hi' : 'en');
}


