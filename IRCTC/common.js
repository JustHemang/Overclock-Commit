function addTransaction(txn) {
  const txns = getTransactions();
  txns.unshift(txn);
  saveTransactions(txns);
}


function getStation(code) {
  return STATIONS.find(s => s.code === code);
}

function getStationName(code) {
  const s = getStation(code);
  return s ? s.name : code;
}

function getStationCity(code) {
  const s = getStation(code);
  return s ? s.city : code;
}

function extractCode(val) {
  const match = val.match(/\(([^)]+)\)/);
  return match ? match[1] : val;
}


function generatePNR() {
  let pnr = '';
  for (let i = 0; i < 10; i++) pnr += Math.floor(Math.random() * 10);
  return pnr.substring(0, 4) + ' ' + pnr.substring(4, 7) + ' ' + pnr.substring(7);
}


function formatDate(dateStr) {
  return new Date(dateStr).toLocaleDateString('en-IN', { weekday: 'short', day: 'numeric', month: 'short', year: 'numeric' });
}

function formatDateShort(dateStr) {
  return new Date(dateStr).toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' });
}

function getTomorrowDate() {
  const d = new Date();
  d.setDate(d.getDate() + 1);
  return d.toISOString().split('T')[0];
}

function getTodayDate() {
  return new Date().toISOString().split('T')[0];
}


function formatCurrency(amount) {
  return '₹' + amount.toLocaleString('en-IN');
}


function animatePageIn() {
  if (typeof gsap === 'undefined') return;
  const cards = document.querySelectorAll('.train-card, .result-card, .offer-card, .bento-card, .booking-card, .stat-item');
  if (cards.length > 0) {
    gsap.fromTo(cards,
      { opacity: 0, y: 16 },
      { opacity: 1, y: 0, stagger: 0.04, duration: 0.35, ease: 'power2.out', delay: 0.1 }
    );
  }
}


function getPageName() {
  const path = window.location.pathname;
  const file = path.split('/').pop() || 'index.html';
  return file.replace('.html', '');
}

