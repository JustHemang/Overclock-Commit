let suggestionHighlight = { from: -1, to: -1 };

function showStationSuggestions(input, type) {
  const val = input.value.toLowerCase().trim();
  const dropdown = document.getElementById(type + 'Suggestions');
  if (!dropdown) return;
  if (val.length < 1) { dropdown.classList.remove('show'); suggestionHighlight[type] = -1; return; }

  const matches = STATIONS.filter(s =>
    s.code.toLowerCase().includes(val) ||
    s.name.toLowerCase().includes(val) ||
    s.city.toLowerCase().includes(val)
  ).slice(0, 8);

  if (matches.length === 0) { dropdown.classList.remove('show'); suggestionHighlight[type] = -1; return; }

  suggestionHighlight[type] = -1;
  dropdown.innerHTML = matches.map((s, i) =>
    `<div class="suggestion-item" data-index="${i}" onclick="selectStation('${s.code}', '${s.name}', '${type}')">
      <span class="s-code">${s.code}</span>
      <span class="s-name">${s.name}, ${s.city}</span>
    </div>`
  ).join('');
  dropdown.classList.add('show');
}

function highlightSuggestion(type, dir) {
  const dropdown = document.getElementById(type + 'Suggestions');
  if (!dropdown || !dropdown.classList.contains('show')) return;
  const items = dropdown.querySelectorAll('.suggestion-item');
  if (items.length === 0) return;

  let idx = suggestionHighlight[type];
  items.forEach(el => el.classList.remove('highlighted'));

  if (dir === 'down') {
    idx = idx < items.length - 1 ? idx + 1 : 0;
  } else {
    idx = idx > 0 ? idx - 1 : items.length - 1;
  }
  suggestionHighlight[type] = idx;
  items[idx].classList.add('highlighted');
  items[idx].scrollIntoView({ block: 'nearest' });
}

function selectHighlightedSuggestion(type) {
  const idx = suggestionHighlight[type];
  if (idx < 0) return false;
  const dropdown = document.getElementById(type + 'Suggestions');
  if (!dropdown) return false;
  const items = dropdown.querySelectorAll('.suggestion-item');
  if (idx >= items.length) return false;
  items[idx].click();
  return true;
}

function handleStationKeydown(input, type, e) {
  const dropdown = document.getElementById(type + 'Suggestions');
  const isOpen = dropdown && dropdown.classList.contains('show');

  if (e.key === 'ArrowDown') {
    e.preventDefault();
    if (!isOpen) showStationSuggestions(input, type);
    else highlightSuggestion(type, 'down');
  } else if (e.key === 'ArrowUp') {
    e.preventDefault();
    if (isOpen) highlightSuggestion(type, 'up');
  } else if (e.key === 'Enter') {
    e.preventDefault();
    if (isOpen && selectHighlightedSuggestion(type)) return;
    const form = input.closest('form');
    if (form) form.dispatchEvent(new Event('submit'));
  } else if (e.key === 'Escape') {
    if (dropdown) dropdown.classList.remove('show');
    suggestionHighlight[type] = -1;
  }
}

function selectStation(code, name, type) {
  const inputId = type === 'from' ? 'fromStation' : 'toStation';
  const input = document.getElementById(inputId);
  if (input) input.value = `${name} (${code})`;
  const hiddenId = type === 'from' ? 'fromStationCode' : 'toStationCode';
  const hidden = document.getElementById(hiddenId);
  if (hidden) hidden.value = code;
  const dropdown = document.getElementById(type + 'Suggestions');
  if (dropdown) dropdown.classList.remove('show');
  suggestionHighlight[type] = -1;
}


